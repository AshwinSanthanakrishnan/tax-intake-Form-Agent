"""Steps 3 and 6: save AI-drafted follow-up emails and document checklists.

Review banners are added here, in code, so no draft can reach a client or a preparer without
being clearly labeled, whatever the model wrote.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass
from datetime import datetime
from pathlib import Path

from .models import FILING_STATUSES, IntakeExtraction
from .redaction import describe_redactions

_RULE = "=" * 72


def save_followup(
    folder: Path,
    source_file: str,
    record: IntakeExtraction,
    draft: str,
    generator: str,
    redacted: dict[str, int] | None = None,
) -> Path:
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / f"{Path(source_file).stem}_followup.txt"
    lines = [
        _RULE,
        "DRAFT - NOT SENT. Intake staff must review and approve before sending.",
        _RULE,
        f"Source email:   {source_file}",
        f"Missing fields: {', '.join(record.missing_field_labels)}",
        f"To:             {record.email or 'UNKNOWN - reply to the original message'}",
        f"Drafted by:     {generator}",
        f"Drafted at:     {datetime.now():%Y-%m-%d %H:%M}",
    ]
    if redacted:
        lines.append(
            f"Staff note:     the client emailed {describe_redactions(redacted)}; it was redacted before AI "
            "processing. Ask them to use a secure channel instead of email."
        )
    header = "\n".join([*lines, "-" * 72])
    path.write_text(f"{header}\n\n{draft.strip()}\n", encoding="utf-8")
    return path


def save_checklist(folder: Path, intake_id: str, record: IntakeExtraction, draft: str, generator: str) -> Path:
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / f"{intake_id}.md"
    filing_status = FILING_STATUSES.get(record.filing_status or "", "not stated")
    content = f"""# Document checklist: {record.tax_year} tax return

> **DRAFT FOR PREPARER REVIEW. NOT TAX ADVICE.**
> Generated automatically as a starting point. A tax preparer must review and adapt it before
> anything is shared with the client.

- **Intake ID:** {intake_id}
- **Tax year:** {record.tax_year}
- **Filing status:** {filing_status}
- **State of residence:** {record.state or "not stated"}
- **Generated by:** {generator}
- **Generated at:** {datetime.now():%Y-%m-%d %H:%M}

{draft.strip()}

---
*Draft for preparer review. Not tax advice. Requirements change; verify against current IRS and
state instructions before relying on this list.*
"""
    path.write_text(content, encoding="utf-8")
    return path


@dataclass(frozen=True)
class ReviewTicket:
    source_file: str
    attempts: int
    errors: list[str]
    raw_outputs: list[str]


def save_review_ticket(folder: Path, ticket: ReviewTicket) -> Path:
    """Record why extraction failed so a person can finish the intake by hand."""
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / f"{Path(ticket.source_file).stem}.json"
    path.write_text(json.dumps(asdict(ticket), indent=2) + "\n", encoding="utf-8")
    return path
